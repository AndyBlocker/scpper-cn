-- v1 TagGuideSync 用 pageUrl(唯一)+ pageVersionId 追踪同步状态。v2:
--   pageUrl       → 保留 page_url(人可读),但唯一键改挂 page_id(身份本位,改名不断链)
--   pageVersionId → last_blob_sha:文档 §5.3 触发矩阵里"约定页 source sha 变化 ⇒
--                   全站归属重解析",sha 才是真正的变更判据;"版本"在 v2 已消亡。
--                   刻意不对 ingest.content_blob 建 FK,以免挡住将来的 blob 回收。
CREATE TABLE IF NOT EXISTS app.tag_guide_sync (
  id             int  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_id        int  NOT NULL UNIQUE REFERENCES ingest.page(id) ON DELETE CASCADE,
  page_url       text,
  last_blob_sha  bytea,
  tags_extracted int  NOT NULL DEFAULT 0,
  last_synced_at timestamptz,
  sync_status    text NOT NULL DEFAULT 'pending',
  error_message  text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tag_guide_sync_status_ck CHECK (sync_status IN ('pending','synced','failed'))
);

COMMENT ON COLUMN app.tag_guide_sync.last_blob_sha IS
  '最后一次同步所依据的 ingest.content_blob.sha256。取代 v1 的 pageVersionId —— §5.3 触发矩阵的判据是"约定页 source sha 变化",sha 是真正的变更信号。';


-- =====================================================================================
-- 词表刷新段(可重复执行时更新已存在表的 CHECK)
-- =====================================================================================
ALTER TABLE app.tag_guide_sync DROP CONSTRAINT IF EXISTS tag_guide_sync_status_ck;
ALTER TABLE app.tag_guide_sync ADD  CONSTRAINT tag_guide_sync_status_ck
  CHECK (sync_status IN ('pending','synced','failed'));

COMMIT;

