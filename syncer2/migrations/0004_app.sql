CREATE TABLE IF NOT EXISTS app.tag_definition (
  id              int  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tag_chinese     text NOT NULL UNIQUE,
  tag_english     text,
  description     text,
  source_page_url text NOT NULL,          -- 人可读来源(如 'tag-guide'),沿用 v1
  source_page_id  int REFERENCES ingest.page(id) ON DELETE SET NULL,  -- v2 增补:身份本位引用
  category        text,
  is_official     boolean NOT NULL DEFAULT true,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
