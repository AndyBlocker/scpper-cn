CREATE OR REPLACE VIEW meta.pending_collection_current AS
WITH fact_high_water AS (
  SELECT last_value::bigint AS seq FROM ingest.fact_seq
),
scan_task AS (
  SELECT 'scan_task:' || st.kind AS collection,
         'scan_task'::text AS family,
         count(*)::bigint AS pending_count,
         min(st.created_at) AS oldest_item_at,
         (array_agg(st.id::text ORDER BY st.created_at, st.id))[1] AS oldest_item_key,
         (st.kind = 'votes_full'
           AND count(*) FILTER (WHERE 'votes_v2_initial_catchup' = ANY(st.reasons))
                 >= count(*) * 0.8)::boolean AS catchup,
         jsonb_build_object(
           'kind', st.kind,
           'due', count(*) FILTER (WHERE st.not_before IS NULL OR st.not_before <= now()),
           'never_attempted', count(*) FILTER (WHERE st.attempts = 0),
           'catchup_items', count(*) FILTER (
             WHERE 'votes_v2_initial_catchup' = ANY(st.reasons)
           ),
           'oldest_attempts', (array_agg(st.attempts ORDER BY st.created_at, st.id))[1],
           'oldest_reasons', (array_agg(to_jsonb(st.reasons) ORDER BY st.created_at, st.id))[1]
         ) AS evidence
    FROM meta.scan_task st
   GROUP BY st.kind
),
revision_ready AS (
  SELECT 'revision_source_backfill:ready'::text AS collection,
         'revision_source_backfill'::text AS family,
         count(*)::bigint AS pending_count,
         min(created_at) AS oldest_item_at,
         (array_agg(revision_seq::text ORDER BY created_at, revision_seq))[1] AS oldest_item_key,
         (count(*) >= 100)::boolean AS catchup,
         jsonb_build_object(
           'pending', count(*) FILTER (WHERE status = 'pending'),
           'retry', count(*) FILTER (WHERE status = 'retry'),
           'due', count(*) FILTER (WHERE not_before <= now()),
           'max_attempts', max(attempts)
         ) AS evidence
    FROM meta.revision_source_backfill_job
   WHERE status IN ('pending','retry')
  HAVING count(*) > 0
),
revision_processing AS (
  SELECT 'revision_source_backfill:processing'::text AS collection,
         'revision_source_backfill_processing'::text AS family,
         count(*)::bigint AS pending_count,
         min(locked_at) AS oldest_item_at,
         (array_agg(revision_seq::text ORDER BY locked_at NULLS FIRST, revision_seq))[1]
           AS oldest_item_key,
         false AS catchup,
         jsonb_build_object('max_attempts', max(attempts)) AS evidence
    FROM meta.revision_source_backfill_job
   WHERE status = 'processing'
  HAVING count(*) > 0
),
irreconcilable AS (
  SELECT 'irreconcilable:' || kind AS collection,
         'irreconcilable'::text AS family,
         count(*)::bigint AS pending_count,
         min(first_seen) AS oldest_item_at,
         (array_agg(
           page_id::text || ':' || COALESCE(instance_id::text, '-')
           ORDER BY first_seen, id
         ))[1] AS oldest_item_key,
         false AS catchup,
         jsonb_build_object(
           'review_due', count(*) FILTER (WHERE next_review_at <= now()),
           'oldest_next_review_at', min(next_review_at),
           'max_checks', max(checks)
         ) AS evidence
    FROM meta.irreconcilable
   WHERE resolved_at IS NULL
   GROUP BY kind
),
projection AS (
  SELECT 'projection_cursor:' || pc.projection AS collection,
         'projection_cursor'::text AS family,
         (h.seq - pc.last_seq)::bigint AS pending_count,
         pc.updated_at AS oldest_item_at,
         pc.projection AS oldest_item_key,
         false AS catchup,
         jsonb_build_object(
           'last_seq', pc.last_seq,
           'fact_high_water', h.seq,
           'event_domain', pc.event_domain
         ) AS evidence
    FROM meta.projection_cursor pc
   CROSS JOIN fact_high_water h
   WHERE pc.last_seq > 0 AND h.seq > pc.last_seq
),
running_run AS (
  SELECT 'ingest_run:running:' || source AS collection,
         'ingest_run'::text AS family,
         count(*)::bigint AS pending_count,
         min(started_at) AS oldest_item_at,
         (array_agg(id::text ORDER BY started_at, id))[1] AS oldest_item_key,
         false AS catchup,
         jsonb_build_object('source', source) AS evidence
    FROM meta.ingest_run
   WHERE status = 'running'
   GROUP BY source
),
drift AS (
  SELECT 'incremental_drift_state:' || kind AS collection,
         'incremental_drift_state'::text AS family,
         count(*)::bigint AS pending_count,
         min(first_detected_at) AS oldest_item_at,
         (array_agg(page_id::text ORDER BY first_detected_at, page_id))[1] AS oldest_item_key,
         false AS catchup,
         jsonb_build_object(
           'max_consecutive_observations', max(consecutive_observations),
           'oldest_last_detected_at', min(last_detected_at)
         ) AS evidence
    FROM meta.incremental_drift_state
   WHERE resolved_at IS NULL
   GROUP BY kind
),
pending_page AS (
  SELECT 'pending_page:' || status AS collection,
         'pending_page'::text AS family,
         count(*)::bigint AS pending_count,
         min(first_seen_at) AS oldest_item_at,
         (array_agg(slug ORDER BY first_seen_at, slug))[1] AS oldest_item_key,
         false AS catchup,
         jsonb_build_object('max_attempts', max(attempts), 'due', count(*) FILTER (
           WHERE not_before IS NULL OR not_before <= now()
         )) AS evidence
    FROM meta.pending_page
   WHERE status IN ('pending','failed','mismatch')
   GROUP BY status
),
forum_task AS (
  SELECT 'forum_scan_task:' || kind AS collection,
         'forum_scan_task'::text AS family,
         count(*)::bigint AS pending_count,
         min(first_seen_at) AS oldest_item_at,
         (array_agg(id::text ORDER BY first_seen_at, id))[1] AS oldest_item_key,
         (count(*) >= 100)::boolean AS catchup,
         jsonb_build_object(
           'due', count(*) FILTER (WHERE not_before IS NULL OR not_before <= now()),
           'max_attempts', max(attempts),
           'max_stable_count', max(stable_count)
         ) AS evidence
    FROM meta.forum_scan_task
   GROUP BY kind
),
observation AS (
  SELECT 'observation_queue:' || status AS collection,
         'observation_queue'::text AS family,
         count(*)::bigint AS pending_count,
         min(enqueued_at) AS oldest_item_at,
         (array_agg(id::text ORDER BY enqueued_at, id))[1] AS oldest_item_key,
         false AS catchup,
         jsonb_build_object('max_attempts', max(attempts)) AS evidence
    FROM meta.observation_queue
   WHERE status IN ('pending','failed')
   GROUP BY status
),
image_job AS (
  SELECT 'image_ingest_job:' || status AS collection,
         'image_ingest_job'::text AS family,
         count(*)::bigint AS pending_count,
         min(CASE WHEN status = 'processing' THEN COALESCE(locked_at, updated_at)
                  ELSE created_at END) AS oldest_item_at,
         (array_agg(id::text ORDER BY
           CASE WHEN status = 'processing' THEN COALESCE(locked_at, updated_at)
                ELSE created_at END, id))[1] AS oldest_item_key,
         (status = 'pending' AND count(*) >= 100)::boolean AS catchup,
         jsonb_build_object('max_attempts', max(attempts)) AS evidence
    FROM meta.image_ingest_job
   WHERE status IN ('pending','processing','failed')
   GROUP BY status
),
page_image AS (
  SELECT 'serve.page_image:' || status AS collection,
         'serve_page_image'::text AS family,
         count(*)::bigint AS pending_count,
         min(COALESCE(last_queued_at, extracted_at)) AS oldest_item_at,
         (array_agg(page_id::text || ':' || normalized_url ORDER BY
           COALESCE(last_queued_at, extracted_at), page_id, normalized_url))[1]
           AS oldest_item_key,
         (status IN ('pending','queued') AND count(*) >= 100)::boolean AS catchup,
         jsonb_build_object('max_failure_count', max(failure_count)) AS evidence
    FROM serve.page_image
   WHERE status IN ('pending','queued','fetching','failed')
   GROUP BY status
),
image_asset AS (
  SELECT 'serve.image_asset:' || status AS collection,
         'serve_image_asset'::text AS family,
         count(*)::bigint AS pending_count,
         min(first_seen_at) AS oldest_item_at,
         (array_agg(encode(hash_sha256, 'hex') ORDER BY first_seen_at, hash_sha256))[1]
           AS oldest_item_key,
         false AS catchup,
         '{}'::jsonb AS evidence
    FROM serve.image_asset
   WHERE status IN ('pending','fetching','failed')
   GROUP BY status
),
vote_catchup AS (
  SELECT 'serve.page_current:vote_snapshot_catchup'::text AS collection,
         'serve_vote_snapshot_catchup'::text AS family,
         count(*)::bigint AS pending_count,
         min(COALESCE(pc.first_published_at, p.created_at)) AS oldest_item_at,
         (array_agg(pc.page_id::text ORDER BY
           COALESCE(pc.first_published_at, p.created_at), pc.page_id))[1] AS oldest_item_key,
         true AS catchup,
         jsonb_build_object(
           'never_complete', count(*) FILTER (
             WHERE pc.last_complete_vote_snapshot_at IS NULL
           )
         ) AS evidence
    FROM serve.page_current pc
    JOIN ingest.page p ON p.id = pc.page_id
    LEFT JOIN meta.vote_sweep_page_state s ON s.page_id = pc.page_id
   WHERE pc.status = 'live' AND s.page_id IS NULL
  HAVING count(*) > 0
),
vote_stale AS (
  SELECT 'serve.page_current:vote_snapshot_stale'::text AS collection,
         'serve_vote_snapshot_stale'::text AS family,
         count(*)::bigint AS pending_count,
         min(pc.last_complete_vote_snapshot_at) AS oldest_item_at,
         (array_agg(pc.page_id::text ORDER BY pc.last_complete_vote_snapshot_at, pc.page_id))[1]
           AS oldest_item_key,
         false AS catchup,
         jsonb_build_object('refresh_contract_days', 30) AS evidence
    FROM serve.page_current pc
    JOIN meta.vote_sweep_page_state s ON s.page_id = pc.page_id
   WHERE pc.status = 'live'
     AND pc.last_complete_vote_snapshot_at < now() - interval '30 days'
  HAVING count(*) > 0
),
l1_stale AS (
  SELECT 'incremental_page_state:l1_stale'::text AS collection,
         'incremental_page_state_l1'::text AS family,
         count(*)::bigint AS pending_count,
         min(COALESCE(ips.last_l1_seen_at, pc.first_published_at, p.created_at)) AS oldest_item_at,
         (array_agg(pc.page_id::text ORDER BY
           COALESCE(ips.last_l1_seen_at, pc.first_published_at, p.created_at), pc.page_id))[1]
           AS oldest_item_key,
         (count(*) >= 100)::boolean AS catchup,
         jsonb_build_object(
           'never_seen_l1', count(*) FILTER (WHERE ips.last_l1_seen_at IS NULL),
           'freshness_contract_minutes', 30
         ) AS evidence
    FROM serve.page_current pc
    JOIN ingest.page p ON p.id = pc.page_id
    LEFT JOIN meta.incremental_page_state ips ON ips.page_id = pc.page_id
   WHERE pc.status = 'live'
     AND (ips.last_l1_seen_at IS NULL OR ips.last_l1_seen_at < now() - interval '30 minutes')
  HAVING count(*) > 0
),
stale_gate AS (
  SELECT 'ingest_gate:stale'::text AS collection,
         'ingest_gate'::text AS family,
         count(*)::bigint AS pending_count,
         min(started_at) AS oldest_item_at,
         (array_agg(txid::text ORDER BY started_at, txid))[1] AS oldest_item_key,
         false AS catchup,
         jsonb_build_object('min_seq_floor', min(seq_floor), 'max_seq_floor', max(seq_floor))
           AS evidence
    FROM meta.ingest_gate
   WHERE COALESCE(txid_status(txid), 'committed') <> 'in progress'
  HAVING count(*) > 0
),
revoke AS (
  SELECT 'revoke_candidate:' || status AS collection,
         'revoke_candidate'::text AS family,
         count(*)::bigint AS pending_count,
         min(first_seen_at) AS oldest_item_at,
         (array_agg(page_id::text || ':' || voter_id::text ORDER BY
           first_seen_at, page_id, voter_id))[1] AS oldest_item_key,
         false AS catchup,
         jsonb_build_object('max_confirmations', max(confirmations)) AS evidence
    FROM meta.revoke_candidate
   WHERE status IN ('pending','held')
   GROUP BY status
),
backfill AS (
  SELECT 'backfill_progress:' || domain || ':' || shard AS collection,
         'backfill_progress'::text AS family,
         GREATEST(total_count - done_count, 0)::bigint AS pending_count,
         updated_at AS oldest_item_at,
         domain || ':' || shard AS oldest_item_key,
         (total_count - done_count >= 100)::boolean AS catchup,
         jsonb_build_object('done_count', done_count, 'total_count', total_count) AS evidence
    FROM meta.backfill_progress
   WHERE done_count < total_count
),
write_freeze AS (
  SELECT 'write_freeze:' || domain AS collection,
         'write_freeze'::text AS family,
         1::bigint AS pending_count,
         frozen_at AS oldest_item_at,
         domain AS oldest_item_key,
         false AS catchup,
         jsonb_build_object('reason', reason, 'alert_after', alert_after) AS evidence
    FROM meta.write_freeze
   WHERE frozen
),
egress_alert AS (
  SELECT 'egress_alert:' || kind AS collection,
         'egress_alert'::text AS family,
         count(*)::bigint AS pending_count,
         min(created_at) AS oldest_item_at,
         (array_agg(id::text ORDER BY created_at, id))[1] AS oldest_item_key,
         false AS catchup,
         '{}'::jsonb AS evidence
    FROM meta.egress_alert
   WHERE acknowledged_at IS NULL
   GROUP BY kind
),
egress_control AS (
  SELECT 'egress_control:' || site_key AS collection,
         'egress_control'::text AS family,
         1::bigint AS pending_count,
         changed_at AS oldest_item_at,
         site_key AS oldest_item_key,
         false AS catchup,
         jsonb_build_object(
           'level', level, 'reason', reason, 'recover_not_before', recover_not_before,
           'budget_breached', budget_breached
         ) AS evidence
    FROM meta.egress_control
   WHERE level > 0 OR budget_breached
),
ambiguous_reference AS (
  SELECT 'serve.page_reference:ambiguous'::text AS collection,
         'serve_page_reference'::text AS family,
         count(*)::bigint AS pending_count,
         min(computed_at) AS oldest_item_at,
         (array_agg(from_page_id::text || ':' || encode(reference_key, 'hex') ORDER BY
           computed_at, from_page_id, reference_key))[1] AS oldest_item_key,
         false AS catchup,
         jsonb_build_object('distinct_target_slugs', count(DISTINCT target_slug)) AS evidence
    FROM serve.page_reference
   WHERE resolution_status = 'ambiguous'
  HAVING count(*) > 0
),
tag_guide_sync AS (
  SELECT 'app.tag_guide_sync:' || sync_status AS collection,
         'app_tag_guide_sync'::text AS family,
         count(*)::bigint AS pending_count,
         min(created_at) AS oldest_item_at,
         (array_agg(id::text ORDER BY created_at, id))[1] AS oldest_item_key,
         false AS catchup,
         jsonb_build_object('oldest_updated_at', min(updated_at)) AS evidence
    FROM app.tag_guide_sync
   WHERE sync_status IN ('pending','failed')
   GROUP BY sync_status
)
