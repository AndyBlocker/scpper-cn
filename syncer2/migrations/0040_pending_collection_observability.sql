CREATE TABLE IF NOT EXISTS meta.pending_collection_sample (
  observed_at              timestamptz NOT NULL,
  collection               text        NOT NULL,
  family                   text        NOT NULL,
  pending_count            bigint      NOT NULL,
  oldest_item_at           timestamptz,
  oldest_item_key          text,
  oldest_age_seconds       bigint,
  catchup                  boolean     NOT NULL DEFAULT false,
  severity                 text        NOT NULL,
  worsening_started_at     timestamptz,
  warn_after_seconds       bigint      NOT NULL,
  critical_after_seconds   bigint      NOT NULL,
  decision                 text        NOT NULL,
  policy_reason            text        NOT NULL,
  evidence                 jsonb       NOT NULL DEFAULT '{}'::jsonb,
  PRIMARY KEY (observed_at, collection),
  CONSTRAINT pcs_count_ck CHECK (pending_count >= 0),
  CONSTRAINT pcs_age_ck CHECK (oldest_age_seconds IS NULL OR oldest_age_seconds >= 0),
  CONSTRAINT pcs_threshold_ck CHECK (
    warn_after_seconds > 0 AND critical_after_seconds >= warn_after_seconds
  ),
  CONSTRAINT pcs_severity_ck CHECK (severity IN ('ok','warn','critical')),
  CONSTRAINT pcs_item_ck CHECK (
    (pending_count = 0 AND oldest_item_at IS NULL AND oldest_item_key IS NULL)
    OR pending_count > 0
  )
);

CREATE INDEX IF NOT EXISTS pcs_collection_time
  ON meta.pending_collection_sample(collection, observed_at DESC);
CREATE INDEX IF NOT EXISTS pcs_alerting_time
  ON meta.pending_collection_sample(severity, observed_at DESC)
  WHERE severity <> 'ok';

CREATE TABLE IF NOT EXISTS meta.pending_collection_alert (
  id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  collection               text        NOT NULL,
  family                   text        NOT NULL,
  severity                 text        NOT NULL,
  started_at               timestamptz NOT NULL,
  first_alerted_at         timestamptz NOT NULL,
  last_alerted_at          timestamptz NOT NULL,
  resolved_at              timestamptz,
  samples                  bigint      NOT NULL DEFAULT 1,
  max_pending_count        bigint      NOT NULL,
  max_oldest_age_seconds   bigint      NOT NULL,
  latest_oldest_item_key   text,
  latest_decision          text        NOT NULL,
  evidence                 jsonb       NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT pca_severity_ck CHECK (severity IN ('warn','critical')),
  CONSTRAINT pca_time_ck CHECK (
    last_alerted_at >= first_alerted_at AND first_alerted_at >= started_at
    AND (resolved_at IS NULL OR resolved_at >= first_alerted_at)
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS pca_one_open_per_collection
  ON meta.pending_collection_alert(collection) WHERE resolved_at IS NULL;
CREATE INDEX IF NOT EXISTS pca_open_severity
  ON meta.pending_collection_alert(severity, started_at) WHERE resolved_at IS NULL;

